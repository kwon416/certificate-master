const DEFAULT_EXAMPLES = [
  '비전공자인데 취업을 위해 자격증을 준비하고 있습니다.',
  '직장인인데 이직을 위해 도움이 될 자격증을 취득하고 싶어요.',
  '경력 단절 후 재취업을 준비 중입니다. 3개월 안에 취득 가능한 것을 찾고 있어요.',
]

export function getContextualExamples(
  situationGoal: string | undefined,
  interestDomain: string | undefined
): string[] {
  // 1. 둘 다 있는 경우: 상황 템플릿에 분야 키워드 삽입
  if (situationGoal && interestDomain) {
    const templates = SITUATION_TEMPLATES[situationGoal]
    const domainLabel = DOMAIN_LABELS[interestDomain] || interestDomain

    if (templates) {
      return templates.map((t) => t.replace(/\{domain\}/g, domainLabel))
    }
  }

  // 2. 상황만 있는 경우
  if (situationGoal && !interestDomain) {
    return SITUATION_ONLY_EXAMPLES[situationGoal] || DEFAULT_EXAMPLES
  }

  // 3. 분야만 있는 경우
  if (!situationGoal && interestDomain) {
    return DOMAIN_ONLY_EXAMPLES[interestDomain] || DEFAULT_EXAMPLES
  }

  // 4. 둘 다 없는 경우
  return DEFAULT_EXAMPLES
}
